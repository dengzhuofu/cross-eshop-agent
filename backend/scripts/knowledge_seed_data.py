def _print_stats() -> None:
    """打印条数与各 category 计数，供人工核对（不写库、不联网）。"""
    print(f"tenant: {TENANT_ID}")
    print(f"total: {len(KNOWLEDGE_SEEDS)}")
    counter = Counter(seed["category"] for seed in KNOWLEDGE_SEEDS)
    for category in CATEGORIES:
        print(f"  {category}: {counter[category]}")
    unknown = sorted(set(counter) - set(CATEGORIES))
    if unknown:
        print(f"  [warn] unexpected categories: {unknown}")
    refs = [seed["ref"] for seed in KNOWLEDGE_SEEDS]
    duplicates = sorted({r for r in refs if refs.count(r) > 1})
    print(f"duplicate refs: {duplicates if duplicates else 'none'}")


if __name__ == "__main__":
    _print_stats()
